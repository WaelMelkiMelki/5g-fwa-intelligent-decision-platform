"""
Regenerate Figure 2.3 (right panel): Validation P2 post-cleaning scatter plot.

Replaces the post-cleaning boxplot of validation_p2_voip.png with a scatter plot
matching the visual style and coordinate system of the left-hand pre-cleaning
panel (p2_voip_anomaly.png) generated by 'Profiling T1-T5.py'.

- Reads polluted and cleaned T5 from PostgreSQL (read-only).
- Recovers the left panel's exact auto-limits by rendering an offscreen clone
  of the polluted-data scatter and reading back get_xlim()/get_ylim().
- Renders all cleaned records in light grey (color='gray', alpha=0.1, s=10,
  identical to the left panel) with the P2 threshold guides:
    vertical line at Social Media Volume = 0 GB
    horizontal line at VoIP Minutes = 5000
- Aborts if the cleaned P2 residual ((voip_minutes > 5000) & (social_media_vol_gb == 0)) != 0.
- Saves to figures/validation_p2_voip.png and copies it to the report figure directories.
"""

import os
import sys
import shutil

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
import pandas as pd
from sqlalchemy import create_engine

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
DB_USER = "postgres"
DB_PASS = __import__("os").environ["FWA_DB_PASSWORD"]
DB_HOST = "localhost"
DB_PORT = "5432"
DB_NAME = "postgres"

ROOT = os.path.dirname(os.path.abspath(__file__))
OUTPUT_PATH = os.path.join(ROOT, "figures", "validation_p2_voip.png")
TARGETS = [
    os.path.join(ROOT, "report_v4", "figures_v3", "validation_p2_voip.png"),
    os.path.join(ROOT, "report_v3", "figures_v3", "validation_p2_voip.png"),
]

P2_VOIP_THRESHOLD = 5000
P2_SOCIAL_THRESHOLD = 0

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def to_num(series):
    return pd.to_numeric(series, errors="coerce")


def load_t5(engine):
    cols = "voip_minutes, social_media_vol_gb"
    polluted = pd.read_sql_query(
        f"SELECT {cols} FROM polluted_data.t5_service_consumption_monthly", engine)
    cleaned = pd.read_sql_query(
        f"SELECT {cols} FROM cleaned_data.t5_service_consumption_monthly", engine)
    return polluted, cleaned


def p2_mask(voip, social):
    return (voip > P2_VOIP_THRESHOLD) & (social == P2_SOCIAL_THRESHOLD)


def recover_left_panel_limits(polluted):
    """Replicate the left panel (Profiling T1-T5.py P2 block) offscreen and
    return its exact axis limits."""
    fig, ax = plt.subplots(figsize=(10, 6))
    ax.scatter(to_num(polluted["social_media_vol_gb"]),
               to_num(polluted["voip_minutes"]),
               alpha=0.1, color="gray", s=10)
    xlim = ax.get_xlim()
    ylim = ax.get_ylim()
    plt.close(fig)
    return xlim, ylim


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    engine = create_engine(
        f"postgresql+psycopg2://{DB_USER}:{DB_PASS}@{DB_HOST}:{DB_PORT}/{DB_NAME}")

    polluted, cleaned = load_t5(engine)

    p2_before = int(p2_mask(to_num(polluted["voip_minutes"]),
                            to_num(polluted["social_media_vol_gb"])).sum())
    p2_after = int(p2_mask(to_num(cleaned["voip_minutes"]),
                           to_num(cleaned["social_media_vol_gb"])).sum())
    print(f"P2 anomalies (voip > {P2_VOIP_THRESHOLD} and social == {P2_SOCIAL_THRESHOLD} GB): "
          f"polluted = {p2_before} | cleaned = {p2_after}")
    if p2_after != 0:
        sys.exit(f"ABORT: cleaned P2 residual is {p2_after}, expected 0.")

    print(f"Polluted extents: voip [{to_num(polluted['voip_minutes']).min():.2f}, "
          f"{to_num(polluted['voip_minutes']).max():.2f}] | "
          f"social [{to_num(polluted['social_media_vol_gb']).min():.2f}, "
          f"{to_num(polluted['social_media_vol_gb']).max():.2f}]")
    print(f"Cleaned extents:  voip [{to_num(cleaned['voip_minutes']).min():.2f}, "
          f"{to_num(cleaned['voip_minutes']).max():.2f}] | "
          f"social [{to_num(cleaned['social_media_vol_gb']).min():.2f}, "
          f"{to_num(cleaned['social_media_vol_gb']).max():.2f}]")

    xlim, ylim = recover_left_panel_limits(polluted)
    print(f"Recovered left-panel auto-limits: xlim = ({xlim[0]:.4f}, {xlim[1]:.4f}) | "
          f"ylim = ({ylim[0]:.4f}, {ylim[1]:.4f})")

    # --- Render the post-cleaning scatter panel ----------------------------
    fig, ax = plt.subplots(figsize=(10, 6))

    ax.scatter(to_num(cleaned["social_media_vol_gb"]),
               to_num(cleaned["voip_minutes"]),
               alpha=0.1, color="gray", s=10,
               label="Cleaned Records")

    ax.axhline(y=P2_VOIP_THRESHOLD, color="red", linestyle="--",
               linewidth=1, alpha=0.5)
    ax.axvline(x=P2_SOCIAL_THRESHOLD, color="red", linestyle="--",
               linewidth=1, alpha=0.5)

    ax.set_xlim(xlim)
    ax.set_ylim(ylim)

    ax.set_xlabel("Social Media Volume (GB)", fontsize=12)
    ax.set_ylabel("VoIP Minutes", fontsize=12)
    ax.set_title("Validation P2: Post-Cleaning VoIP/Social Media Distribution",
                 fontsize=14, fontweight="bold")

    legend_handles = [
        plt.Line2D([0], [0], marker="o", color="none",
                   markerfacecolor="gray", markersize=5, alpha=0.5,
                   label="Cleaned Records"),
        Line2D([0], [0], color="red", linestyle="--", linewidth=1, alpha=0.5,
               label="P2 Threshold"),
    ]
    ax.legend(handles=legend_handles)
    ax.grid(True, alpha=0.3)
    fig.tight_layout()
    fig.savefig(OUTPUT_PATH, dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"Saved: {OUTPUT_PATH}")

    for target in TARGETS:
        os.makedirs(os.path.dirname(target), exist_ok=True)
        shutil.copyfile(OUTPUT_PATH, target)
        print(f"Copied -> {target}")

    print("Done.")


if __name__ == "__main__":
    main()
